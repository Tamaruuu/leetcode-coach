# 扁平化的全部模式列表
ALL_PATTERNS = [p for group in PATTERN_GROUPS.values() for p in group]


def group_of(pattern: str) -> str:
    """返回某个模式所属的大类。"""
    for group, patterns in PATTERN_GROUPS.items():
        if pattern in patterns:
            return group
    return "未分类"
